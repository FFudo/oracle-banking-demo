-- 01_schema.sql
-- Purpose : creates the tables for bank app
-- Run as  : BANK_APP
-- Note    : runs on an empty schema (install.sql recreates BANK_APP first)
pro    Creating TABLE CUSTOMERS...

CREATE TABLE customers (
   customer_id NUMBER GENERATED ALWAYS AS IDENTITY,
   first_name  VARCHAR2(50) NOT NULL,
   last_name   VARCHAR2(50) NOT NULL,
   email       VARCHAR2(254) NOT NULL,
   created_at  TIMESTAMP DEFAULT systimestamp NOT NULL,
   CONSTRAINT customers_pk PRIMARY KEY ( customer_id ),
   CONSTRAINT customers_email_uk UNIQUE ( email ),
   CONSTRAINT customers_email_ck CHECK ( email LIKE '%@%' )
);

COMMENT ON TABLE customers IS
   'every customer in the bank app';

COMMENT ON COLUMN customers.customer_id IS
   'Surrogate primary key, generated by identity column';

COMMENT ON COLUMN customers.first_name IS
   'Customers first name, not null';

COMMENT ON COLUMN customers.last_name IS
   'Customers last name, not null';

COMMENT ON COLUMN customers.email IS
   'Contact email unique per customer';

COMMENT ON COLUMN customers.created_at IS
   'When the customer record was created';


pro    Creating table ACCOUNTS...
CREATE TABLE accounts (
   account_id    NUMBER GENERATED ALWAYS AS IDENTITY,
   customer_id   NUMBER NOT NULL,
   account_type  VARCHAR2(10) NOT NULL,
   status        VARCHAR2(10) DEFAULT 'OPEN' NOT NULL,
   balance       NUMBER(15,2) DEFAULT 0 NOT NULL,
   interest_rate NUMBER(5,4) DEFAULT 0 NOT NULL,
   opened_at     TIMESTAMP DEFAULT systimestamp NOT NULL,
   closed_at     TIMESTAMP,
   CONSTRAINT accounts_pk PRIMARY KEY ( account_id ),
   CONSTRAINT accounts_customer_fk FOREIGN KEY ( customer_id )
      REFERENCES customers ( customer_id ),
   CONSTRAINT accounts_type_ck CHECK ( account_type IN ( 'CHECKING',
                                                         'SAVINGS' ) ),
   CONSTRAINT accounts_status_ck CHECK ( status IN ( 'OPEN',
                                                     'CLOSED' ) ),
   CONSTRAINT accounts_balance_ck CHECK ( balance >= 0 ),
   CONSTRAINT accounts_rate_ck CHECK ( interest_rate BETWEEN 0 AND 0.1 ),
   CONSTRAINT accounts_closed_ck
      CHECK ( ( status = 'OPEN'
         AND closed_at IS NULL )
          OR ( status = 'CLOSED'
         AND closed_at IS NOT NULL ) )
);

COMMENT ON TABLE accounts IS
   'every account in the bank app';

COMMENT ON COLUMN accounts.account_id IS
   'Surrogate primary key, generated by identity column';

COMMENT ON COLUMN accounts.customer_id IS
   'Owner of the account; references CUSTOMERS.customer_id';

COMMENT ON COLUMN accounts.account_type IS
   'Can be Checking or Savings';

COMMENT ON COLUMN accounts.status IS
   'Status of account. Open or Closed. Only Open when closed_at is null';

COMMENT ON COLUMN accounts.balance IS
   'Current balance. Always >= 0';

COMMENT ON COLUMN accounts.interest_rate IS
   'Annual interest rate as a fraction. 0.01 = 1 %. Max. 0.1';

COMMENT ON COLUMN accounts.opened_at IS
   'timestamp of account creation';

COMMENT ON COLUMN accounts.closed_at IS
   'timestamp of accounts closing';

pro    Creating table TRANSACTIONS...
CREATE TABLE transactions (
   txn_id       NUMBER GENERATED ALWAYS AS IDENTITY,
   account_id   NUMBER NOT NULL,
   txn_type     VARCHAR2(12) NOT NULL,
   amount       NUMBER(15,2) NOT NULL,
   transfer_ref NUMBER,
   description  VARCHAR2(200),
   txn_date     TIMESTAMP DEFAULT systimestamp NOT NULL,
   CONSTRAINT transactions_pk PRIMARY KEY ( txn_id ),
   CONSTRAINT transactions_account_fk FOREIGN KEY ( account_id )
      REFERENCES accounts ( account_id ),
   CONSTRAINT transactions_type_ck
      CHECK ( txn_type IN ( 'DEPOSIT',
                            'WITHDRAWAL',
                            'TRANSFER_IN',
                            'TRANSFER_OUT',
                            'INTEREST' ) ),
   CONSTRAINT transactions_amount_ck CHECK ( amount > 0 )
);

COMMENT ON TABLE transactions IS
   'table for all transactions';

COMMENT ON COLUMN transactions.txn_id IS
   'Surrogate primary key, generated by identity column';

COMMENT ON COLUMN transactions.account_id IS
   'Foreign key from accounts table';

COMMENT ON COLUMN transactions.txn_type IS
   'Transaction type. DEPOSIT, WITHDRAWAL, TRANSFER_IN, TRANSFER_OUT, INTEREST';

COMMENT ON COLUMN transactions.amount IS
   'Always positive. Direction comes from txn_type';

COMMENT ON COLUMN transactions.transfer_ref IS
   'Links the TRANSFER_OUT and TRANSFER_IN row of one transfer';

COMMENT ON COLUMN transactions.description IS
   'Description of the transaction';

COMMENT ON COLUMN transactions.txn_date IS
   'Timestamp of transaction';

pro    Creating table AUDIT_LOG...
CREATE TABLE audit_log (
   audit_id    NUMBER GENERATED ALWAYS AS IDENTITY,
   account_id  NUMBER NOT NULL,
   old_balance NUMBER(15,2),
   new_balance NUMBER(15,2) NOT NULL,
   changed_by  VARCHAR2(128) DEFAULT user NOT NULL,
   changed_at  TIMESTAMP DEFAULT systimestamp NOT NULL,
   CONSTRAINT audit_log_pk PRIMARY KEY ( audit_id )
);

COMMENT ON TABLE audit_log IS
   'Balance history per account. No FK on purpose: the log must survive even if an account row is removed.
';

COMMENT ON COLUMN audit_log.audit_id IS
   'Surrogate primary key, generated by identity column';

COMMENT ON COLUMN audit_log.account_id IS
   'Id of account, no foreign key to protect integrity of the log';

COMMENT ON COLUMN audit_log.old_balance IS
   'NULL when account was freshly opened';

COMMENT ON COLUMN audit_log.new_balance IS
   'The new balance';

COMMENT ON COLUMN audit_log.changed_by IS
   'The user who made the balance change';

COMMENT ON COLUMN audit_log.changed_at IS
   'timestamp of the balance change';

pro Creating indexes...
CREATE INDEX accounts_customer_ix ON
   accounts (
      customer_id
   );

CREATE INDEX transactions_account_ix ON
   transactions (
      account_id,
      txn_date
   );

CREATE INDEX audit_log_account_ix ON
   audit_log (
      account_id
   );

pro Creating sequence...
CREATE SEQUENCE transfer_ref_seq;
