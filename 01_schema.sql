-- Purpose : creates the tables for bank app
-- Run as  : BANK_APP
-- Note    : runs on an empty schema (install.sql recreates BANK_APP first)
pro    Creating TABLE CUSTOMERS...

CREATE TABLE customers (
   customer_id NUMBER GENERATED ALWAYS AS IDENTITY,
   first_name  VARCHAR2(50) NOT NULL,
   last_name   VARCHAR2(50) NOT NULL,
   email       VARCHAR2(254) NOT NULL,
   created_at  TIMESTAMP DEFAULT systimestamp NOT NULL,
   CONSTRAINT customers_pk PRIMARY KEY ( customer_id ),
   CONSTRAINT customers_email_uk UNIQUE ( email ),
   CONSTRAINT customer_email_ck CHECK ( email LIKE '%@%' )
);

COMMENT ON TABLE customers IS
   'every customer in the bank app';

COMMENT ON COLUMN customers.customer_id IS
   'Surrogate primary key, generated by identity column';

COMMENT ON COLUMN customers.first_name IS
   'Customers first name, not null';

COMMENT ON COLUMN customers.last_name IS
   'Customers last name, not null';

COMMENT ON COLUMN customers.email IS
   'Contact email unique per customer';

COMMENT ON COLUMN customers.created_at IS
   'When the customer record was created';
